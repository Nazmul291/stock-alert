// anywhere paymentTerms needs a human label instead of the raw stored code
// (PurchaseOrderDetail.tsx, notification emails). currency doesn't need an
// equivalent lookup — it's already stored/displayed as the plain ISO code
// (see currencyPrefix in email-templates.ts), the option label here is only
// for the picker itself.

