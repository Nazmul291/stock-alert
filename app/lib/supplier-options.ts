// Falls back to the raw stored value for suppliers saved before this picker
// existed (free text like "Net 30 days") — never silently blanks out
// existing data just because it doesn't match one of the fixed codes.
export function paymentTermsLabel(value: string | null): string | null {
  if (!value) return null;
  return PAYMENT_TERMS_OPTIONS.find((o) => o.value === value)?.label ?? value;
}

